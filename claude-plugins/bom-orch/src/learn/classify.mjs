/**
 * §7.1 태스크 분류 — LLM 없이, 정규식만으로 0ms 에 끝낸다.
 *
 * ★ 테스트 보유 여부는 여기서 새로 탐색하지 않는다. `deriveTestCommand(projectPath).source`
 *   (`package.json`·`csproj`·`Makefile`·`pytest.ini`·`pyproject.toml`, 못 찾으면 결과 자체가
 *   `null`)가 이미 그것이다. 엔진이 그 값을 뽑아 `testSource` 로 넘긴다.
 *
 * ★ 규칙은 고정 우선순위 하나다: PROSE 가 걸리면 prose, 아니면 CODE 가 걸리면 code,
 *   둘 다 아니면 analysis. `analysis` 는 "애매하니 넓은 쪽" 이 아니라 **두 정규식이 모두
 *   안 걸렸을 때의 낙하지점**이다. 애매한 문장이 analysis 로 간다는 보장은 없다 —
 *   `test/_classify-corpus.mjs` 의 행들이 그 반례다:
 *     '이 저장소가 무슨 일을 하는지 요약해줘'  -> prose
 *     '이 버그가 왜 나는지 설명해줘'           -> code:test-bearing
 *     'CHANGELOG 에 2.1 …추가해줘'             -> prose
 *
 * ★ PROSE 를 CODE 보다 먼저 보는 근거는 **총 오분류가 아니라 비용 비대칭**이다. 코퍼스
 *   96행을 `의도`(사람이 읽은 정답) 기준으로 두 순서로 채점하면 PROSE 먼저 17, CODE 먼저 28
 *   로 PROSE 먼저가 크게 이긴다 — 그런데 **그 우세는 근거로 쓸 수 없다.** 코퍼스는 키워드와
 *   함께 쓴 문장들이라 순서 실험에도 같이 과적합돼 있다. 코퍼스 밖 홀드아웃 54문장에서는
 *   총계가 뒤집힌다: PROSE 먼저 35, CODE 먼저 26.
 *
 *   순서를 고른 것은 총계가 아니라 방향이다. 문서 의도 27문장(홀드아웃 문서 15 + 명사 치환
 *   12)이 code 셀로 새는 수는 PROSE 먼저 19, CODE 먼저 22 이고 코퍼스 안에서는 0 대 15 다.
 *   반대 방향(코드 의도 27문장이 prose 로 새는 것)은 PROSE 먼저 13, CODE 먼저 1 이라 총계는
 *   CODE 먼저가 가져간다. 두 방향의 값이 다르기 때문에 총계가 아니라 비싼 쪽을 보고 골랐다.
 *   그 방향이 왜 비싼지는 아래 CODE 정규식 주석에 적었다.
 *   (재현: `test/learn-classify.test.mjs` 의 "두 순서를 `의도` 기준으로 채점한다" 가 위 수를
 *   전부 계산한다. 아래 두 `if` 를 손으로 바꾸면 첫 테스트가 19행 붉어지는데, 그것은 `기대`
 *   기준이라 여기 숫자와 다른 것을 센다 — 두 수를 섞어 읽지 마라.)
 *
 * 여기서 하지 않는 것 둘:
 * - 확장자 기반 재정의(.cs/.ts/.py 는 코드, .md/.txt 는 산문). `task` 는 자유 문장이라 파일
 *   경로가 안 나오는 경우가 흔하고(분석 요청 태반이 그렇다), 나오는 경우에도 키워드와
 *   충돌할 수 있어("README.md 파서의 버그를 고쳐줘" 는 .md 가 붙었지만 코드 요청이다)
 *   규칙이 하나 더 늘 뿐 애매함이 줄지 않는다.
 *   `orch_run` 은 파일 목록을 인자로 받지도 않는다(`src/tools.mjs`).
 * - 한국어 전용 CODE 동사(추가해·삭제해·옮겨·바꿔·세팅해…)의 영어 대응. 그래서
 *   "Please add a caching layer" 류 영어 코드 요청은 analysis 로 간다 — 코퍼스에 7행이
 *   그렇게 남아 있다. 이것을 "무해하다" 고 읽지 마라. analysis 셀에 코드 실행이 섞이고
 *   code 셀의 표본이 그만큼 줄어드는 것은 실제 손해다. 다만 새는 방향이 문서→code 만큼
 *   비싸지는 않아서(아래 참조) 뒤로 미뤘다. PROSE 쪽 영어 명사(changelog·license·guide…)는
 *   넣었다 — 그쪽은 비싼 방향을 막는 데 필요해서다.
 */
export const TASK_CLASSES = Object.freeze(['code:test-bearing', 'code:no-tests', 'prose', 'analysis']);

/**
 * 문서를 만들거나 고치라는 요청.
 *
 * 명사 위주다. 문서 요청은 동사를 코드와 공유하기 때문이다("CHANGELOG 에 …**추가해**줘",
 * "오래된 노트를 **삭제해**줘") — 대상 명사가 없으면 그 문장들은 전부 CODE 로 넘어간다.
 * 예외는 동사 `정리해` 하나다. 왜 여기 있는지는 아래 CODE 주석의 4-way 표에 적었다.
 *
 * `주석` 은 여기 없다. 다른 명사는 전부 별도 문서 파일(README·CHANGELOG·가이드…)을
 * 가리키는데 주석만 소스 파일 안에 있어서, "주석을 추가해줘" 의 실행은 워커가 소스를
 * 편집하고 테스트가 그 파일을 실제로 임포트하는 code 실행과 같다.
 *
 * ★ 이 목록을 넓혀서 "문서→code 유출" 을 없애려 하지 마라. 코퍼스에서 그 수가 0 인 것은
 *   **이 목록의 성질이지 분류기의 성질이 아니다.** 통제 실험이 그것을 보였다 — 코퍼스
 *   문서 12행에서 **명사만** 목록 밖 동의어로 바꾸고(변경 이력·저작권 고지·안내서·참고서·
 *   규약·메모·페이지·지침서·안내문·개요) 동사와 구조는 그대로 두면 **0/12 가 11/12** 로
 *   뒤집힌다. 그 지표가 재는 것은 "내가 이 목록에 넣은 명사를 썼는가" 다.
 *
 *   구조적인 이유가 있다: **CODE 확장은 열린 동사 집합이라 일반화하고, PROSE 확장은 닫힌
 *   명사 목록이라 일반화하지 않는다.** 게다가 여기 명사들은 경계 없는 부분 문자열이라
 *   넓힐수록 반대 방향이 샌다 — 지금도 `docsearch`·`LicenseManager`·`레퍼런스 카운팅`·
 *   `DocumentBuilder` 가 든 코드 요청이 prose 로 간다.
 *
 *   그래서 넓히지 않았다. 대신 `test/_classify-corpus.mjs` 의 홀드아웃 배열 셋(문서 15 ·
 *   명사 치환 12 · 코드 27)이 두 방향의 현재 유출 수를 들고 있다. 이 정규식을 건드리는
 *   사람은 그 숫자가 어느 쪽으로 움직이는지 보고 판단하면 된다.
 */
const PROSE =
  /(문서|readme|요약|번역|정리해|써줘|작성해|설명문|설명서|가이드|매뉴얼|튜토리얼|위키|레퍼런스|노트|라이선스|changelog|license|contributing|guide|tutorial|wiki|document|docs)/i;

/**
 * 코드를 바꾸라는 요청.
 *
 * `(?!야)` 는 "…해야 할지 판단해줘" 류를 뺀다. 그 문장은 코드를 바꾸라는 요청이 아니라
 * 바꿀지 묻는 질문이고, 그대로 code 셀에 들어가면 워커가 답만 쓰고 끝낸 실행이 그 셀의
 * 표본이 된다. 아래 문단의 오염과 **방향은 같고 경로는 다르다** — 답만 쓴 실행은 패치가
 * 비어서 `engine.mjs` 의 빈 패치 경로가 `unverified` 로 내리고 notice 를 붙이는 반면,
 * 마크다운 편집은 패치가 비지 않아 그 경로를 통째로 피한다. 계획 3 문서(`:1255` 등급 표)
 * 기준 `unverified` 는 어떤 셀도 갱신하지 않으므로(`gradeToDeltas('unverified') === null`,
 * 같은 문서 `:877`), 걱정의 종류는 같아도 아래쪽이 더 비싸다.
 *
 * ★ 이 정규식을 넓힐 때 PROSE 도 같이 보라. 가장 비싼 오분류는 **문서 요청이
 *   `code:test-bearing` 으로 가는 것**이다: 마크다운만 고친 실행은 패치가 비어 있지 않아
 *   `engine.mjs` 의 빈 패치 경고(M-3)에 걸리지 않고, 테스트 스위트는 그 변경 전에도
 *   통과하므로 `verified` 가 나온다. 계획 3 문서 기준 그 등급은 taskClass 셀의 보상이
 *   되므로 그 셀에 "아무것도 안 해도 최고 등급" 이 쌓인다(`engine.mjs` M-3 주석이 지목한
 *   위험과 같은 것이다). 반대 방향(코드 요청이 prose 로 새는 것)은 셀을 섞을 뿐 이 되먹임을
 *   만들지 않는다.
 *
 * `정리해` 는 PROSE 에 있다. 한 번 여기(CODE)로 옮겼다가 되돌렸다. 옮겼을 때 적었던
 * "싼 방향 두 칸을 얻고 비싼 방향 한 칸을 잃는다" 는 재 보지 않은 수였고, 4-way 로 다시
 * 재니 **1:1 교환**이었다(세 홀드아웃, 두 위치, 각각 실측):
 *
 *     정리해 위치        문서 홀드아웃 code 유출   코드 홀드아웃 오분류   코드→prose 유출
 *     PROSE (지금)                 8                    15                   13
 *     CODE                         9                    14                   12
 *
 * 뒤바뀐 행은 양쪽 각각 정확히 하나다 — CODE 로 옮기면 "개발 환경 설정 방법을 정리해서
 * 올려줘"(문서 의도)를 code 셀로 잃고 "이 코드를 정리해줘"(코드 의도)를 얻는다. 비싼
 * 방향 한 칸을 내주고 싼 방향 한 칸을 받는 거래라 위 비대칭 논리에 어긋난다. 게다가 얻는
 * 쪽 문장은 `정리해` 를 옮기자고 이름 댄 표본 안에 있었고 잃는 쪽은 표본 밖이라, 일반화
 * 증거도 이동에 불리하다. 그래서 PROSE 로 되돌렸다.
 *
 * 되돌린 대가는 라벨에 남는다: "src/utils.py 파일을 정리해줘"·"사용하지 않는 import 를
 * 정리해줘" 는 prose 로 간다. 그것을 "정답" 이라 부르지 않고 코퍼스의 `의도` 열에
 * `code:*` 로 적었다 — 그 두 행은 알고 남겨둔 오분류다.
 *
 * `달아` 는 "이 함수에 주석을 달아줘" 하나 때문에 넣었다. 주석 편집을 code 로 보기로
 * 했으면서(위 PROSE 주석) 그 문장만 analysis 로 흘리고 있었다.
 */
const CODE =
  /((고쳐|수정해|추가해|삭제해|옮겨|바꿔|최적화해|세팅해|만들어|달아)(?!야)|버그|구현|리팩터|테스트를? 만들|fix|bug|implement|refactor)/i;

/**
 * 분류의 진입점은 `classifyTask` 하나다. 두 정규식을 내보내는 것은 순서 실험(PROSE 먼저 vs
 * CODE 먼저)을 저장소 안에서 재현하려고 테스트가 같은 객체를 쓰게 하기 위해서다 — 복사본을
 * 두면 여기를 고쳐도 그쪽이 안 따라온다.
 */
export const CLASSIFY_PATTERNS = Object.freeze({ PROSE, CODE });

export function classifyTask(spec) {
  const options = spec !== null && typeof spec === 'object' ? spec : {};
  const task = typeof options.task === 'string' ? options.task : '';
  const hasTests = typeof options.testSource === 'string' && options.testSource !== '';

  if (PROSE.test(task)) return 'prose';
  if (CODE.test(task)) return hasTests ? 'code:test-bearing' : 'code:no-tests';
  return 'analysis';
}
